import Feather from '@expo/vector-icons/Feather';
import { useRouter } from 'expo-router';
import { useMemo, useState } from 'react';
import { Pressable, View } from 'react-native';

import { alertsApi } from '@/api/endpoints/alerts';
import { orgApi } from '@/api/endpoints/org';
import type { SafetyAlert } from '@/api/types';
import { SeverityBadge } from '@/components/domain/Badges';
import {
  Badge,
  Banner,
  Button,
  Card,
  ConfirmSheet,
  EmptyState,
  Field,
  Header,
  Screen,
  Segmented,
  SkeletonCard,
  Text,
} from '@/components/ui';
import { REGIONS_BY_ID } from '@/constants/regions';
import { SEVERITY_META } from '@/constants/threats';
import { useQuery } from '@/hooks/use-query';
import { useNow } from '@/hooks/use-now';
import { formatRadius } from '@/lib/geo';
import { pluralize, timeAgo, timeUntil } from '@/lib/format';
import { useToast } from '@/state/toast';
import { useTheme } from '@/theme';

/**
 * Alerts an officer has issued.
 *
 * Includes both kinds: those generated by verifying a report, and standalone
 * advisories. Withdrawing an advisory is prominent here because a stale
 * restriction that nobody cancelled is how teams learn to ignore advisories.
 */
export default function AdvisoriesScreen() {
  const { spacing } = useTheme();
  const router = useRouter();
  const toast = useToast();

  const [tab, setTab] = useState<'active' | 'all'>('active');
  const [cancelTarget, setCancelTarget] = useState<SafetyAlert | null>(null);
  const [cancelReason, setCancelReason] = useState('');
  const [cancelling, setCancelling] = useState(false);

  const alerts = useQuery({
    key: `alerts.list.${tab}`,
    fetcher: () => alertsApi.list({ includeExpired: tab === 'all' }),
    watch: ['alerts'],
  });

  const directory = useQuery({ key: 'org.directory', fetcher: () => orgApi.directory() });

  const grouped = useMemo(() => {
    const list = alerts.data ?? [];
    return {
      advisories: list.filter((a) => a.kind === 'advisory'),
      threats: list.filter((a) => a.kind === 'threat'),
    };
  }, [alerts.data]);

  const confirmCancel = async () => {
    if (!cancelTarget) return;
    setCancelling(true);
    try {
      await alertsApi.cancel(cancelTarget.id, cancelReason || 'No longer applicable.');
      toast.success('Advisory withdrawn', 'It no longer appears in workers’ active feeds.');
      setCancelTarget(null);
      setCancelReason('');
      await alerts.refetch();
    } catch (e) {
      const error = e as { userMessage?: string };
      toast.error('Could not withdraw', error.userMessage ?? 'Try again.');
    } finally {
      setCancelling(false);
    }
  };

  return (
    <>
      <Screen refreshing={alerts.isRefreshing} onRefresh={() => void alerts.refetch()} extraBottomPadding={40}>
        <Header
          title="Advisories"
          subtitle="Standing guidance and the alerts your verifications produced"
          right={
            <Button label="New" icon="plus" size="sm" onPress={() => router.push('/advisory/new')} />
          }
        />

        <View style={{ gap: spacing.xl }}>
          <Segmented
            options={[
              { value: 'active', label: 'Active' },
              { value: 'all', label: 'Including expired' },
            ]}
            value={tab}
            onChange={setTab}
          />

          {alerts.isLoading && !alerts.data ? (
            <View style={{ gap: spacing.md }}>
              <SkeletonCard />
              <SkeletonCard />
            </View>
          ) : (
            <>
              {/* Standalone advisories */}
              <View style={{ gap: spacing.md }}>
                <Text variant="label" tone="tertiary">
                  Standing advisories ({grouped.advisories.length})
                </Text>

                {grouped.advisories.length === 0 ? (
                  <EmptyState
                    compact
                    icon="volume-2"
                    title="No advisories"
                    message="Issue one when guidance applies beyond a single incident - a movement curfew, a corridor restriction, a comms outage."
                    action={{ label: 'Issue an advisory', onPress: () => router.push('/advisory/new'), icon: 'plus' }}
                  />
                ) : (
                  grouped.advisories.map((alert) => (
                    <AlertCard
                      key={alert.id}
                      alert={alert}
                      issuerName={directory.data?.[alert.issuedBy]?.name ?? 'Unknown'}
                      onCancel={() => setCancelTarget(alert)}
                      onOpen={() => router.push({ pathname: '/alert/[id]', params: { id: alert.id } })}
                    />
                  ))
                )}
              </View>

              {/* Verification-generated alerts */}
              <View style={{ gap: spacing.md }}>
                <Text variant="label" tone="tertiary">
                  From verified reports ({grouped.threats.length})
                </Text>

                {grouped.threats.length === 0 ? (
                  <Banner
                    tone="neutral"
                    icon="inbox"
                    message="Alerts appear here automatically when you verify a report. You do not issue them separately."
                  />
                ) : (
                  grouped.threats.slice(0, 20).map((alert) => (
                    <AlertCard
                      key={alert.id}
                      alert={alert}
                      issuerName={directory.data?.[alert.issuedBy]?.name ?? 'Unknown'}
                      onOpen={() =>
                        alert.relatedReportId
                          ? router.push({ pathname: '/report/[id]', params: { id: alert.relatedReportId } })
                          : router.push({ pathname: '/alert/[id]', params: { id: alert.id } })
                      }
                    />
                  ))
                )}
              </View>
            </>
          )}
        </View>
      </Screen>

      <ConfirmSheet
        visible={!!cancelTarget}
        onClose={() => setCancelTarget(null)}
        onConfirm={confirmCancel}
        loading={cancelling}
        title="Withdraw this advisory?"
        confirmLabel="Withdraw"
        message={`"${cancelTarget?.title}" will stop appearing as active for the ${pluralize(cancelTarget?.recipientCount ?? 0, 'person', 'people')} who received it. The record is kept.`}
      >
        <Field
          label="Reason"
          placeholder="e.g. Corridor reopened after security assessment"
          value={cancelReason}
          onChangeText={setCancelReason}
          icon="message-square"
          maxLength={200}
        />
      </ConfirmSheet>
    </>
  );
}

function AlertCard({
  alert,
  issuerName,
  onCancel,
  onOpen,
}: {
  alert: SafetyAlert;
  issuerName: string;
  onCancel?: () => void;
  onOpen: () => void;
}) {
  const { colors, spacing } = useTheme();
  const now = useNow(60_000);
  const expired = alert.expiresAt ? Date.parse(alert.expiresAt) < now : false;
  const cancelled = !!alert.cancelledAt;
  const inactive = expired || cancelled;

  return (
    <Card
      accent={colors[SEVERITY_META[alert.severity].colorKey]}
      onPress={onOpen}
      accessibilityLabel={alert.title}
      style={{ opacity: inactive ? 0.6 : 1 }}
    >
      <View style={{ gap: spacing.md }}>
        <View style={{ flexDirection: 'row', alignItems: 'center', gap: spacing.sm, flexWrap: 'wrap' }}>
          <SeverityBadge severity={alert.severity} size="sm" />
          {alert.kind === 'advisory' ? <Badge label="Advisory" icon="volume-2" size="sm" /> : <Badge label="From report" icon="file-text" size="sm" />}
          {cancelled ? (
            <Badge label="Withdrawn" size="sm" color={colors.textTertiary} />
          ) : expired ? (
            <Badge label="Expired" size="sm" color={colors.textTertiary} />
          ) : null}
        </View>

        <Text variant="bodyStrong">{alert.title}</Text>
        <Text variant="footnote" tone="secondary" numberOfLines={3}>
          {alert.message}
        </Text>

        <View style={{ flexDirection: 'row', flexWrap: 'wrap', gap: spacing.md }}>
          <Meta icon="users" text={pluralize(alert.recipientCount, 'recipient')} />
          {alert.radiusMeters ? <Meta icon="radio" text={formatRadius(alert.radiusMeters)} /> : null}
          {alert.regionIds.length ? (
            <Meta icon="map" text={alert.regionIds.map((r) => REGIONS_BY_ID[r]?.name ?? r).join(', ')} />
          ) : null}
          <Meta icon="user" text={issuerName} />
        </View>

        <View style={{ flexDirection: 'row', alignItems: 'center', justifyContent: 'space-between' }}>
          <Text variant="caption" tone="tertiary">
            Issued {timeAgo(alert.createdAt)}
          </Text>
          {alert.expiresAt && !inactive ? (
            <Text variant="caption" tone="tertiary">
              Expires {timeUntil(alert.expiresAt)}
            </Text>
          ) : null}
        </View>

        {onCancel && !inactive ? (
          <Pressable onPress={onCancel} hitSlop={8} accessibilityRole="button" style={{ flexDirection: 'row', alignItems: 'center', gap: 5 }}>
            <Feather name="x-circle" size={13} color={colors.danger} />
            <Text variant="footnote" tone="danger" weight="600">
              Withdraw
            </Text>
          </Pressable>
        ) : null}
      </View>
    </Card>
  );
}

function Meta({ icon, text }: { icon: keyof typeof Feather.glyphMap; text: string }) {
  const { colors } = useTheme();
  return (
    <View style={{ flexDirection: 'row', alignItems: 'center', gap: 4, maxWidth: '100%' }}>
      <Feather name={icon} size={11} color={colors.textTertiary} />
      <Text variant="caption" tone="tertiary" numberOfLines={1}>
        {text}
      </Text>
    </View>
  );
}
